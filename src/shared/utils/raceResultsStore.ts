const FALLBACK_IMAGES = [
  '/images/results-running.jpg',
  '/images/hero-running.jpg',
  '/images/camisetas.jpg',
  '/images/cuellos.jpg',
];

const normalizeResults = (results: RaceResult[]): RaceResult[] =>
  results.map((item, index) => ({
    ...item,
    id: item.id || `${item.dorsal}-${index}`,
  }));

const normalizeRace = (race: RaceEvent): RaceEvent => ({
  ...race,
  coverImage: race.coverImage || FALLBACK_IMAGES[Math.abs(race.id.length) % FALLBACK_IMAGES.length],
  results: normalizeResults(race.results || []),
});

// Used by public pages — falls back to demo data when nothing is stored
export const loadRaces = (): RaceEvent[] => {
  if (typeof window === 'undefined') return DEFAULT_RACES;

  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw === null) return DEFAULT_RACES; // key never set → show demos

    const parsed = JSON.parse(raw) as RaceEvent[];
    if (!Array.isArray(parsed)) return DEFAULT_RACES;
    return parsed.map(normalizeRace);
  } catch {
    return DEFAULT_RACES;
  }
};

// Used by admin & mutations — returns only what is actually stored (no demo fallback)
export const loadRawRaces = (): RaceEvent[] => {
  if (typeof window === 'undefined') return [];

  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return [];

    const parsed = JSON.parse(raw) as RaceEvent[];
    if (!Array.isArray(parsed)) return [];

    // Deduplicate by ID — keep the entry with more results (or the last one)
    const seen = new Map<string, RaceEvent>();
    for (const race of parsed) {
      const existing = seen.get(race.id);
      if (!existing || (race.results?.length ?? 0) >= (existing.results?.length ?? 0)) {
        seen.set(race.id, race);
      }
    }
    return Array.from(seen.values()).map(normalizeRace);
  } catch {
    return [];
  }
};

export const saveRaces = (races: RaceEvent[]) => {
  if (typeof window === 'undefined') return;
  localStorage.setItem(STORAGE_KEY, JSON.stringify(races));
};

export const upsertRace = (race: RaceEvent) => {
  const races = loadRawRaces();
  const idx = races.findIndex((item) => item.id === race.id);

  if (idx >= 0) {
    races[idx] = race;
  } else {
    races.unshift(race);
  }

  saveRaces(races);
  return races;
};

export const deleteRace = (raceId: string) => {
  const races = loadRawRaces().filter((item) => item.id !== raceId);
  saveRaces(races);
  return races;
};

export const updateRaceResults = (raceId: string, results: RaceResult[]) => {
  const races = loadRawRaces();
  const idx = races.findIndex((item) => item.id === raceId);
  if (idx < 0) return races;

  races[idx] = {
    ...races[idx],
    results: normalizeResults(results),
  };

  saveRaces(races);
  return races;
};

/**
 * Garantiza que exista un RaceEvent para el HomeEvent dado.
 * Si no existe, lo crea con resultados vacíos.
 * Si ya existe, NO lo modifica (preserva resultados).
 */
export const ensureRaceExists = (event: { id: string; name: string; date: string; location: string; coverImage?: string }): void => {
  const races = loadRawRaces();
  const exists = races.some(r => r.id === event.id);
  if (!exists) {
    upsertRace({
      id: event.id,
      name: event.name,
      date: event.date,
      location: event.location,
      coverImage: event.coverImage ?? '/images/results-running.jpg',
      results: [],
    });
  }
};
